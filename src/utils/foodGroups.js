// 关键词容易误伤的词：命中左边就去掉右边的类
const FOOD_EXCEPT = [
  ['蛋糕', '肉蛋鱼'], ['蛋挞', '肉蛋鱼'], ['奶粉', '主食'], ['牛奶', '肉蛋鱼'], ['奶黄', '奶豆'],
  ['果冻', '水果'], ['果泥', ''], ['虾米', '主食'], ['菜饭', ''], ['米糊', ''],
]

// 返回猜到的大类数组（可能多个，如「西兰花牛肉粥」→ 主食 / 蔬菜 / 肉蛋鱼），猜不出返回 []
export function guessFoodGroups(name) {
  const n = name || ''
  const hit = new Set()
  for (const [g, words] of Object.entries(FOOD_WORDS)) {
    if (words.some(w => n.includes(w))) hit.add(g)
  }
  for (const [w, drop] of FOOD_EXCEPT) if (drop && n.includes(w)) hit.delete(drop)
  return FOOD_GROUPS.map(g => g.key).filter(k => hit.has(k))
}

